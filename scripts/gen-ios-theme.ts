/// <reference types="node" /> // Node-only: reads/writes files (the app itself stays browser-only)
// Writes the iPhone app's color tokens from the web themes, so both apps share one palette.
// Run from frontend/ (so its packages resolve):  npx tsx ../scripts/gen-ios-theme.ts
// frontend/src/ios-theme.test.ts fails when the Swift file is out of date.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DEFAULT_MODE, DEFAULT_THEME, THEMES, darkColors } from "../frontend/src/themes";

const OUT = "../ios/ByteSizeKit/Sources/ByteSizeKit/Theme/ThemeTokens.swift";

const dict = (colors: Record<string, string>, indent: string) =>
  "[\n" +
  Object.keys(colors)
    .sort()
    .map((k) => `${indent}    "${k}": "${colors[k]}",`)
    .join("\n") +
  `\n${indent}]`;

export function renderSwiftTokens(): string {
  const themes = THEMES.map(
    (t) =>
      `        "${t.id}": ThemeTokenSet(\n` +
      `            name: ${JSON.stringify(t.name)},\n` +
      `            light: ${dict(t.colors, "            ")},\n` +
      `            dark: ${dict(darkColors(t), "            ")}\n` +
      `        ),`,
  ).join("\n");
  return (
    "// GENERATED by scripts/gen-ios-theme.ts from frontend/src/themes.ts — do not edit.\n\n" +
    "struct ThemeTokenSet: Sendable {\n    let name: String\n    let light: [String: String]\n    let dark: [String: String]\n}\n\n" +
    "enum ThemeTokens {\n" +
    `    static let defaultTheme = "${DEFAULT_THEME}"\n` +
    `    static let defaultMode = "${DEFAULT_MODE}"\n` +
    `    static let order = [${THEMES.map((t) => `"${t.id}"`).join(", ")}]\n` +
    "    static let all: [String: ThemeTokenSet] = [\n" +
    themes +
    "\n    ]\n}\n"
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = fileURLToPath(new URL(OUT, import.meta.url));
  writeFileSync(out, renderSwiftTokens());
  console.log(`Wrote ${out}`);
}
